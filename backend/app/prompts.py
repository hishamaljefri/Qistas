MAX_DOCUMENT_CHARS_IN_PROMPT = 12000


def build_user_prompt(
    masked_description: str,
    articles_block: str,
    known_facts: list[str] | None = None,
    documents: list[tuple[str, str]] | None = None,
    today: date | None = None,
) -> str:
    """documents: (masked filename, masked extracted text) pairs."""
    facts = ("معلومات أدخلها المستخدم في النموذج:\n" + "\n".join(f"- {f}" for f in known_facts) + "\n\n") if known_facts else ""
    docs = ""
    for name, text in documents or []:
        body = text if len(text) <= MAX_DOCUMENT_CHARS_IN_PROMPT else text[:MAX_DOCUMENT_CHARS_IN_PROMPT] + " …(مقتطع)"
        docs += f"\n\n--- مستند مرفق: {name} (نص مستخرج آلياً) ---\n{body}"
    day = f"تاريخ اليوم: {today:%Y-%m-%d}\n\n" if today else ""
    return f"""المواد النظامية المتاحة (لا تعتمد على غيرها):
{articles_block}

---
{day}{facts}وصف الحالة من المستخدم:
{masked_description}{docs}

حلّل الحالة وفق القواعد، وأجب بصيغة JSON المطلوبة."""


